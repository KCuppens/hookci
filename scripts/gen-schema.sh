#!/usr/bin/env bash
# Generates Go and TypeScript types from schema/hookci.schema.json. Idempotent.
# Usage: scripts/gen-schema.sh [outdir]
# Files are written at their repo-relative paths under outdir, which defaults
# to the repo root. scripts/schema-check.sh passes a temp dir.
set -euo pipefail

cd "$(dirname "$0")/.."
out=$(cd "${1:-.}" && pwd)

json2ts=schema/node_modules/.bin/json2ts
if [ ! -x "$json2ts" ]; then
	echo "gen-schema: $json2ts not found; run 'cd schema && npm ci'" >&2
	exit 1
fi

banner='// Code generated by scripts/gen-schema.sh. DO NOT EDIT.'
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

mkdir -p "$out/agent/internal/config" "$out/agent/internal/protocol" "$out/hub/src/config" "$out/hub/src/protocol"
cp schema/hookci.schema.json "$out/agent/internal/config/hookci.schema.json"

# protocol.schema.json: $defs.protocol as its own root, with its refs
# rewritten from #/$defs/protocol/$defs/X to #/$defs/X.
# config.schema.json: the full schema without $defs.protocol, which would
# otherwise become an empty `type Protocol interface{}` in package config.
node -e '
const fs = require("fs");
const [src, protocolOut, configOut] = process.argv.slice(1);
const schema = JSON.parse(fs.readFileSync(src, "utf8"));
const protocol = {
  $schema: schema.$schema,
  $id: "https://ci.webuno.io/schema/protocol.schema.json",
  title: "Protocol",
  ...schema.$defs.protocol,
};
const protocolJSON = JSON.stringify(protocol, null, 2).replaceAll("\"#/$defs/protocol/$defs/", "\"#/$defs/");
fs.writeFileSync(protocolOut, protocolJSON + "\n");
delete schema.$defs.protocol;
fs.writeFileSync(configOut, JSON.stringify(schema, null, 2) + "\n");
' schema/hookci.schema.json "$tmp/protocol.schema.json" "$tmp/config.schema.json"

(
	cd agent
	go run github.com/atombender/go-jsonschema --package protocol --only-models --tags json \
		-o "$out/agent/internal/protocol/types_gen.go" "$tmp/protocol.schema.json"
	go run github.com/atombender/go-jsonschema --package config --struct-name-from-title --tags json,yaml \
		-o "$out/agent/internal/config/types_gen.go" "$tmp/config.schema.json"
)

"$json2ts" -i schema/hookci.schema.json -o "$out/hub/src/config/generated.ts" --bannerComment "$banner"
"$json2ts" -i "$tmp/protocol.schema.json" -o "$out/hub/src/protocol/types.gen.ts" --unreachableDefinitions --bannerComment "$banner"

# Replace the generator's own header line with the shared banner.
for f in "$out/agent/internal/protocol/types_gen.go" "$out/agent/internal/config/types_gen.go"; do
	node -e '
const fs = require("fs");
const [file, banner] = process.argv.slice(1);
const lines = fs.readFileSync(file, "utf8").split("\n");
if (lines[0].startsWith("// Code generated")) lines.shift();
fs.writeFileSync(file, banner + "\n" + lines.join("\n"));
' "$f" "$banner"
done
gofmt -w "$out/agent/internal/protocol/types_gen.go" "$out/agent/internal/config/types_gen.go"

echo "gen-schema: ok"
