#!/usr/bin/env bash
# Generates Go and TypeScript types from schema/zeroci.schema.json. Idempotent.
set -euo pipefail

cd "$(dirname "$0")/.."

banner='// Code generated by scripts/gen-schema.sh. DO NOT EDIT.'
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cp schema/zeroci.schema.json agent/internal/config/zeroci.schema.json

# protocol.schema.json: $defs.protocol as its own root.
# config.schema.json: the full schema without $defs.protocol, which would
# otherwise become an empty `type Protocol interface{}` in package config.
node -e '
const fs = require("fs");
const [src, protocolOut, configOut] = process.argv.slice(1);
const schema = JSON.parse(fs.readFileSync(src, "utf8"));
const protocol = {
  $schema: schema.$schema,
  $id: "https://ci.webuno.io/schema/protocol.schema.json",
  title: "Protocol",
  ...schema.$defs.protocol,
};
fs.writeFileSync(protocolOut, JSON.stringify(protocol, null, 2) + "\n");
delete schema.$defs.protocol;
fs.writeFileSync(configOut, JSON.stringify(schema, null, 2) + "\n");
' schema/zeroci.schema.json "$tmp/protocol.schema.json" "$tmp/config.schema.json"

(
	cd agent
	go run github.com/atombender/go-jsonschema --package protocol --only-models --tags json \
		-o internal/protocol/types_gen.go "$tmp/protocol.schema.json"
	go run github.com/atombender/go-jsonschema --package config --struct-name-from-title --tags json,yaml \
		-o internal/config/types_gen.go "$tmp/config.schema.json"
)

(
	cd hub
	mkdir -p src/config src/protocol
	npx json2ts -i ../schema/zeroci.schema.json -o src/config/generated.ts --bannerComment "$banner"
	npx json2ts -i "$tmp/protocol.schema.json" -o src/protocol/generated.ts --unreachableDefinitions --bannerComment "$banner"
)

# Replace the generator's own header line with the shared banner.
for f in agent/internal/protocol/types_gen.go agent/internal/config/types_gen.go; do
	node -e '
const fs = require("fs");
const [file, banner] = process.argv.slice(1);
const lines = fs.readFileSync(file, "utf8").split("\n");
if (lines[0].startsWith("// Code generated")) lines.shift();
fs.writeFileSync(file, banner + "\n" + lines.join("\n"));
' "$f" "$banner"
done
gofmt -w agent/internal/protocol/types_gen.go agent/internal/config/types_gen.go

echo "gen-schema: ok"
