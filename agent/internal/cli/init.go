package cli

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/KCuppens/zerocideploy/agent/internal/detect"
)

func runInit(_ context.Context, args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	fs.SetOutput(stderr)

	var force bool
	fs.BoolVar(&force, "f", false, "overwrite existing config file")
	fs.BoolVar(&force, "force", false, "overwrite existing config file")

	fs.Usage = func() {
		fmt.Fprintln(stdout, "Usage: zeroci init [flags] [path]")
		fmt.Fprintln(stdout)
		fmt.Fprintln(stdout, "Scaffold a .zeroci.yml configuration file for the detected ecosystem.")
		fmt.Fprintln(stdout)
		fmt.Fprintln(stdout, "Flags:")
		fs.SetOutput(stdout)
		fs.PrintDefaults()
	}

	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return ExitOK
		}
		return ExitUsage
	}

	targetPath := ".zeroci.yml"
	detectDir := "."

	if fs.NArg() > 0 {
		arg := fs.Arg(0)
		if strings.HasSuffix(arg, ".yml") || strings.HasSuffix(arg, ".yaml") {
			targetPath = arg
			detectDir = filepath.Dir(arg)
		} else {
			targetPath = filepath.Join(arg, ".zeroci.yml")
			detectDir = arg
		}
	}

	if _, err := os.Stat(targetPath); err == nil && !force {
		fmt.Fprintf(stderr, "zeroci: %s already exists (use --force to overwrite)\n", targetPath)
		return ExitUsage
	}

	res, err := detect.Detect(detectDir)
	if err != nil {
		if errors.Is(err, detect.ErrNoEcosystemDetected) {
			fmt.Fprintf(stderr, "zeroci: no supported project ecosystem detected in %s\n", detectDir)
			return ExitNoChecks
		}
		fmt.Fprintf(stderr, "zeroci: detection failed: %v\n", err)
		return ExitUsage
	}

	yamlBytes, err := detect.FormatYAML(res.Config)
	if err != nil {
		fmt.Fprintf(stderr, "zeroci: failed to format yaml: %v\n", err)
		return ExitInternal
	}

	header := fmt.Sprintf("# ZeroCI configuration file (.zeroci.yml)\n# Auto-generated by zeroci init (Ecosystem: %s)\n\n", res.Ecosystem)
	finalContent := append([]byte(header), yamlBytes...)

	if err := os.WriteFile(targetPath, finalContent, 0o644); err != nil {
		fmt.Fprintf(stderr, "zeroci: failed to write %s: %v\n", targetPath, err)
		return ExitInternal
	}

	fmt.Fprintf(stdout, "Initialized %s (%s detected)\n", targetPath, res.Ecosystem)
	return ExitOK
}
