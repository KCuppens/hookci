#!/usr/bin/env node
// Writes hub/src/legal/content.ts from docs/legal/*.md, docs/support.md and
// SECURITY.md, so the pages the hub serves are the documents in the repository.
// npm runs it before test and build; test/well-known.test.ts fails when the
// committed module has drifted from the documents.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * The generated module. Each source becomes one entry of LEGAL_DOCS, named by
 * its lowercased file name without .md: privacy, terms, support, security.
 * @param {Record<string, string>} sources markdown keyed by its file path
 * @returns {string}
 */
export function legalModule(sources) {
	const docs = Object.entries(sources).map(([path, markdown]) => [path.slice(path.lastIndexOf("/") + 1, -".md".length).toLowerCase(), markdown]);
	const entries = docs.sort(([a], [b]) => (a < b ? -1 : 1)).map(([name, markdown]) => `\t${name}: ${JSON.stringify(markdown)},`);
	return [
		"// Generated by hub/scripts/gen-legal.mjs from docs/legal/*.md, docs/support.md",
		"// and SECURITY.md. Do not edit: change the document and run npm run gen:legal.",
		"",
		"export const LEGAL_DOCS = {",
		...entries,
		"} as const;",
		"",
	].join("\n");
}

if (import.meta.main) {
	const repo = new URL("../../", import.meta.url);
	const paths = [
		...readdirSync(new URL("docs/legal/", repo))
			.filter((name) => name.endsWith(".md"))
			.map((name) => `docs/legal/${name}`),
		"docs/support.md",
		"SECURITY.md",
	];
	const sources = Object.fromEntries(paths.map((path) => [path, readFileSync(new URL(path, repo), "utf8")]));
	const out = new URL("../src/legal/content.ts", import.meta.url);
	writeFileSync(out, legalModule(sources));
	console.log(`wrote ${fileURLToPath(out)}`);
}
